-- Aplicar a la base seleccionada después de 011. Los pedidos previos siguen su flujo de entrega.
CREATE TABLE IF NOT EXISTS cotizacion_castores (
  id INT AUTO_INCREMENT PRIMARY KEY,
  comprador_id INT NOT NULL,
  metodo_pago ENUM('tarjeta','paypal','mercadopago','transferencia') NOT NULL,
  proveedor_id INT NOT NULL,
  direccion_id INT NOT NULL,
  solicitud CHAR(64) CHARACTER SET ascii UNIQUE,
  productos JSON NOT NULL,
  destino VARCHAR(180) NOT NULL,
  cp_destino CHAR(5) NOT NULL,
  comision_estimada DECIMAL(12,2) NOT NULL,
  valor_mercancia DECIMAL(12,2) NOT NULL,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cp_origen CHAR(5) DEFAULT NULL,
  referencia VARCHAR(100) DEFAULT NULL,
  fuente ENUM('cotizador','envia','sandbox') DEFAULT NULL,
  embalaje JSON DEFAULT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 0,
  servicio VARCHAR(100) DEFAULT NULL,
  vigencia DATE DEFAULT NULL,
  flete DECIMAL(12,2) DEFAULT NULL,
  otros_costos_estimados DECIMAL(12,2) DEFAULT NULL,
  motivo_rechazo VARCHAR(200) DEFAULT NULL,
  pedido_id INT DEFAULT NULL UNIQUE,
  guia VARCHAR(40) DEFAULT NULL UNIQUE,
  canal_guia ENUM('castores','envia','sandbox') DEFAULT NULL,
  costo_flete_real DECIMAL(12,2) DEFAULT NULL,
  recibido_por VARCHAR(100) DEFAULT NULL,
  acuse VARCHAR(150) DEFAULT NULL,
  confirmacion ENUM('comprador','administracion') DEFAULT NULL,
  confirmado_por INT DEFAULT NULL,
  incidencia VARCHAR(240) DEFAULT NULL,
  KEY idx_castores_proveedor (proveedor_id,pedido_id,id),
  FOREIGN KEY (comprador_id) REFERENCES usuario(id),
  FOREIGN KEY (confirmado_por) REFERENCES usuario(id) ON DELETE SET NULL,
  FOREIGN KEY (proveedor_id) REFERENCES proveedor(id),
  FOREIGN KEY (pedido_id) REFERENCES pedido(id)
) ENGINE=InnoDB;
